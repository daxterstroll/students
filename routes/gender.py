"""
routes/gender.py
================
Визначення статі студента за по батькові (українська традиція).

Використовується при:
  - додаванні нового студента (якщо в формі обрано «Авто»)
  - редагуванні студента (якщо стать ще не визначена)
  - імпорті з Excel (якщо колонка «Стать» порожня)

Окремий модуль, щоб функція була доступна і з routes/students/core.py,
і з routes/students/import_export.py, і з майбутнього migrate-скрипта
для військового обліку — без дублювання.

Примітка: якщо в студента немає по батькові (іноземець, неповні дані) —
функція повертає None, і стать треба заповнити вручну в картці.
"""


# Жіночі закінчення по батькові в українській мові
FEMALE_SUFFIXES = (
    'івна',   # Іванівна, Петрівна
    'ївна',   # Сергіївна, Андріївна
    'овна',   # (рідше, але буває)
    'евна',   # (рідше)
    'євна',   # (рідше)
    'ична',   # Іллічна, Кузьмічна (від «Ілля», «Кузьма»)
)


def detect_gender_from_middle_name(middle_name):
    """
    Визначає стать за по батькові.

    Args:
        middle_name: по батькові (укр.), може бути None/порожнім

    Returns:
        'F' (жіноча), 'M' (чоловіча) або None (не визначено)
    """
    if not middle_name:
        return None

    # Нормалізуємо апострофи та регістр
    m = str(middle_name).strip().lower()
    m = m.replace('’', "'").replace('ʼ', "'").replace('‘', "'")

    if not m:
        return None

    if m.endswith(FEMALE_SUFFIXES):
        return 'F'
    return 'M'